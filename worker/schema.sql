CREATE TABLE IF NOT EXISTS users (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  username TEXT NOT NULL UNIQUE COLLATE NOCASE,
  salt TEXT NOT NULL,
  pass_hash TEXT NOT NULL,
  face TEXT,
  best INTEGER NOT NULL DEFAULT 0,
  games INTEGER NOT NULL DEFAULT 0,
  total_dodged INTEGER NOT NULL DEFAULT 0,
  eaten INTEGER NOT NULL DEFAULT 0,
  coins INTEGER NOT NULL DEFAULT 0,
  donuts INTEGER NOT NULL DEFAULT 0,
  owned_skins INTEGER NOT NULL DEFAULT 1,
  owned_shoes INTEGER NOT NULL DEFAULT 1,
  cape_owned INTEGER NOT NULL DEFAULT 0,
  cape_active INTEGER NOT NULL DEFAULT 0,
  approved INTEGER NOT NULL DEFAULT 0,
  story_level INTEGER NOT NULL DEFAULT 1,
  skin_tone INTEGER NOT NULL DEFAULT 2,
  shoe_color INTEGER NOT NULL DEFAULT 0,
  is_admin INTEGER NOT NULL DEFAULT 0,
  created_at INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS sessions (
  token TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL,
  expires_at INTEGER NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id);
